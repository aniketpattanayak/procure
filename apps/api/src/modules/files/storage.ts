import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join, resolve, sep } from 'node:path';

/** Where file bytes live (ADR-0008). `app.file_object` is the catalogue; drivers only move bytes. */
export interface StorageDriver {
  readonly kind: 'local' | 's3';
  put(key: string, body: Buffer, mime: string): Promise<void>;
  get(key: string): Promise<Buffer>;
  delete(key: string): Promise<void>;
  /**
   * A directly downloadable URL for the object, or null when the API must stream it (local driver: the API signs its
   * own `/files/:id/content` URLs instead).
   */
  presign(key: string, opts: { filename: string; mime: string; ttlSec: number; inline: boolean }): Promise<string | null>;
}

/** Storage keys are generated by the API; still, never let one escape the root. */
function safeJoin(root: string, key: string): string {
  if (!/^[A-Za-z0-9/_.-]+$/.test(key) || key.includes('..')) throw new Error(`invalid storage key ${key}`);
  const p = resolve(root, key);
  if (!p.startsWith(resolve(root) + sep)) throw new Error(`storage key escapes root: ${key}`);
  return p;
}

export class LocalStorageDriver implements StorageDriver {
  readonly kind = 'local' as const;
  constructor(readonly root: string) {}

  async put(key: string, body: Buffer): Promise<void> {
    const p = safeJoin(this.root, key);
    await mkdir(dirname(p), { recursive: true });
    await writeFile(p, body);
  }

  async get(key: string): Promise<Buffer> {
    return readFile(safeJoin(this.root, key));
  }

  async delete(key: string): Promise<void> {
    await rm(safeJoin(this.root, key), { force: true });
  }

  async presign(): Promise<string | null> {
    return null;
  }

  /** Disk cache for derived files (thumbnails). */
  cachePath(key: string): string {
    return safeJoin(join(this.root, '.cache'), key);
  }
}

export class S3StorageDriver implements StorageDriver {
  readonly kind = 's3' as const;
  private readonly s3: S3Client;
  constructor(private readonly bucket: string, region: string, endpoint?: string) {
    this.s3 = new S3Client({ region, endpoint, forcePathStyle: !!endpoint });
  }

  async put(key: string, body: Buffer, mime: string): Promise<void> {
    await this.s3.send(new PutObjectCommand({ Bucket: this.bucket, Key: key, Body: body, ContentType: mime }));
  }

  async get(key: string): Promise<Buffer> {
    const r = await this.s3.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    const bytes = await r.Body?.transformToByteArray();
    return Buffer.from(bytes ?? []);
  }

  async delete(key: string): Promise<void> {
    await this.s3.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }

  async presign(key: string, o: { filename: string; mime: string; ttlSec: number; inline: boolean }): Promise<string> {
    const disposition = `${o.inline ? 'inline' : 'attachment'}; filename="${o.filename.replace(/["\\\r\n]/g, '_')}"`;
    return getSignedUrl(
      this.s3,
      new GetObjectCommand({ Bucket: this.bucket, Key: key, ResponseContentType: o.mime, ResponseContentDisposition: disposition }),
      { expiresIn: o.ttlSec },
    );
  }
}
